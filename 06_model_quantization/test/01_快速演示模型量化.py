# 步骤 06-6｜量化最小 demo：两层全连接模型，看量化前后的结构变化

import sys  # 控制台输出编码容错：Windows 的 GBK 控制台打印乱码字符会直接报错

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

import torch
import torch.nn as nn  # 神经网络模块
# 导入Torch AO的INT8动态量化配置
from torchao.quantization import Int8DynamicActivationInt8WeightConfig
# 导入Torch AO的量化函数
from torchao.quantization import quantize_

# =======================================
# 1. 创建一个最简单的两层全连接模型
# ========================================

# 使用 Sequential 按顺序组合多个网络层
model = nn.Sequential(
    # 第一层全连接层
    # 输入特征数是 128
    # 输出特征数是 256
    nn.Linear(128, 256),

    # 激活函数
    nn.ReLU(),

    # 第二层全连接层
    # 输入特征数是 256
    # 输出特征数是 10
    nn.Linear(256, 10)
)

# =========================================================
# 2. 切换到推理模式
# =========================================================

# 告诉模型：现在不是训练，而是准备预测
model.eval()

# =========================================================
# 3. 打印量化前模型
# =========================================================

# 打印提示文字
print(
    "量化前模型："
)

# 打印模型结构
print(
    model
)

# =========================================================
# 4. 创建 INT8 动态量化配置
# =========================================================

# 创建 INT8 动态 Activation + INT8 Weight 配置
quant_config = (
    Int8DynamicActivationInt8WeightConfig()
)

# =========================================================
# 5. 执行量化
# =========================================================

# quantize_ 会按照 quant_config 的规则修改 model
quantize_(
    model,
    quant_config
)

# =========================================================
# 6. 打印量化后的模型
# =========================================================

# 打印提示文字
print(
    "量化后模型："
)

# 打印量化后的模型结构
print(
    model
)

# =========================================================
# 7. 准备一条模拟输入
# =========================================================

# 创建形状为 [1, 128] 的随机输入
# 1 表示一条样本
# 128 表示 128 个输入特征
x = torch.randn(
    1,
    128
)

# =========================================================
# 8. 模型推理
# =========================================================

# 关闭梯度计算，提高推理效率
with torch.inference_mode():
    # 把输入交给模型
    output = model(x)

# =========================================================
# 9. 查看输出形状
# =========================================================

# 打印输出 Tensor 的形状
print(
    "输出形状：",
    output.shape
)
